FR_HINT = re.compile(r"[àâäçéèêëîïôöùûüÿœÀÂÄÇÉÈÊËÎÏÔÖÙÛÜŸŒ]|\b(?:le|la|les|des|du|de|dans|pour|avec|sans|sur|et|ou|une|un|est|sont|si|quand|depuis|vers|aucun|aucune|champ|couche|hauteur|vue|rendu|paramètres|calcul|choisir|afficher|ajouter|erreur|impossible)\b", re.I)


def template_from_fstring(node):
    out=[]; idx=1
    for v in node.values:
        if isinstance(v, ast.Constant) and isinstance(v.value, str):
            out.append(v.value)
        else:
            out.append(f"%{idx}"); idx += 1
    return "".join(out)


def translate_text(source):
    if source in EXACT:
        return EXACT[source]
    text=source
    for a,b in REPLACEMENTS:
        text=text.replace(a,b)
    return text


def is_docstring_node(parent, node):
    if not isinstance(parent, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return False
    return bool(parent.body and parent.body[0] is node)


def collect_python_sources():
    values=set()
    for p in list(ROOT.glob("*.py")) + list((ROOT/"core").glob("*.py")) + list((ROOT/"ui").glob("*.py")):
        if p.name == "_i18n.py":
            continue
        try:
            tree=ast.parse(p.read_text(encoding="utf-8"))
        except Exception:
            continue
        parents={}
        for parent in ast.walk(tree):
            for child in ast.iter_child_nodes(parent):
                parents[child]=parent
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                parent=parents.get(node)
                if isinstance(parent, ast.Expr) and is_docstring_node(parents.get(parent), parent):
                    continue
                text=node.value.strip()
                if text and (text in EXACT or FR_HINT.search(text)) and len(text) <= 1200:
                    values.add(text)
            elif isinstance(node, ast.JoinedStr):
                text=template_from_fstring(node).strip()
                if text and (text in EXACT or FR_HINT.search(text)) and len(text) <= 1200:
                    values.add(text)
    return values


def collect_ui_sources():
    contexts={}
    for p in (ROOT/"ui").glob("*.ui"):
        try:
            tree=ET.parse(p)
        except Exception:
            continue
        root=tree.getroot()
        ctx=(root.findtext("class") or "QCALVIEW").strip()
        vals=contexts.setdefault(ctx,set())
        for node in root.findall(".//string"):
            text=(node.text or "").strip()
            if not text or text.startswith("QFrame#") or text.startswith("font-weight"):
                continue
            vals.add(text)
    return contexts


def indent_xml(elem, level=0):
    pad="\n" + "  "*level
    if len(elem):
        if not elem.text or not elem.text.strip(): elem.text=pad+"  "
        for child in elem:
            indent_xml(child, level+1)
        if not elem[-1].tail or not elem[-1].tail.strip(): elem[-1].tail=pad
    if level and (not elem.tail or not elem.tail.strip()): elem.tail=pad


def write_ts(language, identity=False):
    ts=ET.Element("TS", version="2.1", language=("fr_FR" if language=="fr" else "en_US"), sourcelanguage="fr_FR")
    pyctx=ET.SubElement(ts,"context"); ET.SubElement(pyctx,"name").text="QCALVIEW"
    for source in sorted(collect_python_sources()):
        msg=ET.SubElement(pyctx,"message")
        ET.SubElement(msg,"source").text=source
        ET.SubElement(msg,"translation").text=(source if identity else translate_text(source))
    for ctx, values in sorted(collect_ui_sources().items()):
        c=ET.SubElement(ts,"context"); ET.SubElement(c,"name").text=ctx
        for source in sorted(values):
            msg=ET.SubElement(c,"message")
            ET.SubElement(msg,"source").text=source
            ET.SubElement(msg,"translation").text=(source if identity else translate_text(source))
    indent_xml(ts)
    ET.ElementTree(ts).write(I18N/f"QCALVIEW_{language}.ts", encoding="utf-8", xml_declaration=True)


def audit_english():
    bad=[]
    for source in sorted(collect_python_sources() | {x for vals in collect_ui_sources().values() for x in vals}):
        trans=translate_text(source)
        if FR_HINT.search(source) and (trans == source or FR_HINT.search(trans)):
            bad.append((source,trans))
    return bad


